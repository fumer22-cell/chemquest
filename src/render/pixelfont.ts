/** Tiny 3×5 pixel font for equipment displays. */
const GLYPHS: Record<string, string> = {
  '0': '111101101101111', '1': '010110010010111', '2': '111001111100111', '3': '111001111001111',
  '4': '101101111001001', '5': '111100111001111', '6': '111100111101111', '7': '111001010010010',
  '8': '111101111101111', '9': '111101111001111', '.': '000000000000010', '-': '000000111000000',
  ' ': '000000000000000', '°': '010101010000000', C: '111100100100111', g: '000111101111001',
  m: '000110111101101', L: '100100100100111', O: '111101101101111', F: '111100110100100',
  N: '101111111111101', E: '111100110100111', A: '010101111101101', R: '110101110101101',
  H: '101101111101101', T: '111010010010010', P: '110101110100100', S: '111100111001111',
  I: '111010010010111', D: '110101101101110', U: '101101101101111', V: '101101101101010',
  ':': '000010000010000', '%': '101001010100101', '/': '001001010100100', x: '000101010101000',
  M: '101111111101101', B: '110101110101110', G: '111100101101111', K: '101101110101101',
  W: '101101111111101', Y: '101101010010010', J: '001001001101111', Q: '111101101111001',
  X: '101101010101101', Z: '111001010100111', '+': '000010111010000',
};

export function drawText(
  buf: Uint8ClampedArray,
  W: number,
  H: number,
  x: number,
  y: number,
  text: string,
  rgb: [number, number, number],
): number {
  let cx = x;
  for (const ch of text) {
    const g = GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS[' '];
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < 3; c++) {
        if (g[r * 3 + c] !== '1') continue;
        const px = cx + c;
        const py = y + r;
        if (px < 0 || py < 0 || px >= W || py >= H) continue;
        const i = (py * W + px) * 4;
        buf[i] = rgb[0];
        buf[i + 1] = rgb[1];
        buf[i + 2] = rgb[2];
        buf[i + 3] = 255;
      }
    }
    cx += 4;
  }
  return cx - x;
}

export const textWidth = (t: string) => t.length * 4 - 1;
